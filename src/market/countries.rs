/// Get the long English name for a country code or name.
/// E.g. "US" -> "United States", "VE" -> "Venezuela", "WORLDWIDE" -> "WorldWide", "UNKNOWN" -> "Unknown".
pub fn country_name(code_or_name: &str) -> String {
    let trimmed = code_or_name.trim();
    if trimmed.is_empty() {
        return String::new();
    }
    if trimmed.eq_ignore_ascii_case("worldwide") {
        return "WorldWide".to_string();
    }
    if trimmed.eq_ignore_ascii_case("unknown") {
        return "Unknown".to_string();
    }
    // Match by code first
    for (code, name) in ISO_COUNTRIES {
        if code.eq_ignore_ascii_case(trimmed) {
            return name.to_string();
        }
    }
    // If not matching code directly, resolve to 2-letter code first (via alias/prefix), then look up canonical name
    let resolved_code = country_code(trimmed);
    if !resolved_code.is_empty() && !resolved_code.eq_ignore_ascii_case(trimmed) {
        for (code, name) in ISO_COUNTRIES {
            if code.eq_ignore_ascii_case(&resolved_code) {
                return name.to_string();
            }
        }
    }
    // Match by name
    for (_, name) in ISO_COUNTRIES {
        if name.eq_ignore_ascii_case(trimmed) {
            return name.to_string();
        }
    }
    trimmed.to_string()
}

/// Get the standard 2-letter uppercase ISO code (or "WorldWide" / "Unknown") for a country code or name.
/// E.g. "United States" -> "US", "us" -> "US", "Venezuela" -> "VE", "WorldWide" -> "WorldWide".
pub fn country_code(code_or_name: &str) -> String {
    let trimmed = code_or_name.trim();
    if trimmed.is_empty() {
        return String::new();
    }
    if trimmed.eq_ignore_ascii_case("worldwide") {
        return "WorldWide".to_string();
    }
    if trimmed.eq_ignore_ascii_case("unknown") {
        return "Unknown".to_string();
    }
    // Match by code
    for (code, _) in ISO_COUNTRIES {
        if code.eq_ignore_ascii_case(trimmed) {
            return code.to_uppercase();
        }
    }
    // Match common aliases from IP intelligence databases
    let lower = trimmed.to_lowercase();
    for (alias, code) in COMMON_ALIASES {
        if *alias == lower {
            return code.to_uppercase();
        }
    }
    // Match by exact name
    for (code, name) in ISO_COUNTRIES {
        if name.eq_ignore_ascii_case(trimmed) {
            return code.to_uppercase();
        }
    }
    // Prefix / suffix matching for composite official country names
    // E.g. "Venezuela, Bolivarian..." or "Bolivia (Plurinational...)"
    for (code, name) in ISO_COUNTRIES {
        let name_lower = name.to_lowercase();
        if lower.starts_with(&name_lower) {
            let rest = &lower[name_lower.len()..];
            if rest.starts_with(',') || rest.starts_with(" (") || rest.starts_with(" of") || rest.starts_with(" -") {
                return code.to_uppercase();
            }
        }
    }
    trimmed.to_uppercase()
}

/// Normalize any country string (short code or long name) to standard representation.
pub fn normalize_country(code_or_name: &str) -> String {
    let trimmed = code_or_name.trim();
    if trimmed.eq_ignore_ascii_case("worldwide") {
        return "WorldWide".to_string();
    }
    if trimmed.eq_ignore_ascii_case("unknown") {
        return "Unknown".to_string();
    }
    country_code(trimmed)
}

/// Generate the unicode flag emoji for a country code or country name.
/// E.g. "US" or "United States" -> "🇺🇸", "VE" or "Venezuela" -> "🇻🇪", "WorldWide" -> "🌐", "Unknown" -> "❓".
pub fn country_flag(code_or_name: &str) -> String {
    let trimmed = code_or_name.trim();
    if trimmed.is_empty() {
        return String::new();
    }
    if trimmed.eq_ignore_ascii_case("worldwide") {
        return "🌐".to_string();
    }
    if trimmed.eq_ignore_ascii_case("unknown") {
        return "❓".to_string();
    }
    let code = country_code(trimmed);
    if code.eq_ignore_ascii_case("worldwide") {
        return "🌐".to_string();
    }
    if code.eq_ignore_ascii_case("unknown") {
        return "❓".to_string();
    }
    if code.len() == 2 && code.chars().all(|c| c.is_ascii_alphabetic()) {
        let mut chars = code.chars();
        let c1 = chars.next().unwrap().to_ascii_uppercase();
        let c2 = chars.next().unwrap().to_ascii_uppercase();
        let cp1 = 0x1F1E6 + (c1 as u32 - 'A' as u32);
        let cp2 = 0x1F1E6 + (c2 as u32 - 'A' as u32);
        if let (Some(ch1), Some(ch2)) = (char::from_u32(cp1), char::from_u32(cp2)) {
            return format!("{}{}", ch1, ch2);
        }
    }
    String::new()
}

#[derive(Debug, Clone, serde::Serialize, serde::Deserialize, PartialEq, Eq)]
pub struct CountryMetadata {
    pub country: String,
    pub country_code: String,
    pub country_name: String,
    pub flag_emoji: String,
}

/// Get structured country metadata (code, canonical long name, and flag emoji).
pub fn country_metadata(code_or_name: &str) -> CountryMetadata {
    let code = country_code(code_or_name);
    let name = country_name(&code);
    let flag = country_flag(&code);
    CountryMetadata {
        country: code.clone(),
        country_code: code,
        country_name: name,
        flag_emoji: flag,
    }
}

/// Get complete list of metadata for all officially recognized ISO countries plus special regions.
pub fn all_country_metadata() -> Vec<CountryMetadata> {
    let mut list = Vec::with_capacity(ISO_COUNTRIES.len());
    for (code, name) in ISO_COUNTRIES {
        list.push(CountryMetadata {
            country: code.to_string(),
            country_code: code.to_string(),
            country_name: name.to_string(),
            flag_emoji: country_flag(code),
        });
    }
    list
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_country_name_and_code_roundtrip() {
        assert_eq!(country_name("US"), "United States");
        assert_eq!(country_code("United States"), "US");
        assert_eq!(country_code("united states"), "US");
        assert_eq!(country_name("VE"), "Venezuela");
        assert_eq!(country_code("Venezuela"), "VE");
        assert_eq!(country_name("TJ"), "Tajikistan");
        assert_eq!(country_code("Tajikistan"), "TJ");
        assert_eq!(country_name("WorldWide"), "WorldWide");
        assert_eq!(country_code("WorldWide"), "WorldWide");
        assert_eq!(country_name("Unknown"), "Unknown");
        assert_eq!(country_code("Unknown"), "Unknown");
    }

    #[test]
    fn test_country_flags() {
        assert_eq!(country_flag("US"), "🇺🇸");
        assert_eq!(country_flag("United States"), "🇺🇸");
        assert_eq!(country_flag("VE"), "🇻🇪");
        assert_eq!(country_flag("Venezuela"), "🇻🇪");
        assert_eq!(country_flag("TJ"), "🇹🇯");
        assert_eq!(country_flag("Tajikistan"), "🇹🇯");
        assert_eq!(country_flag("WorldWide"), "🌐");
        assert_eq!(country_flag("Unknown"), "❓");
        assert_eq!(country_flag(""), "");

        let meta = country_metadata("United States");
        assert_eq!(meta.country_code, "US");
        assert_eq!(meta.country_name, "United States");
        assert_eq!(meta.flag_emoji, "🇺🇸");

        let all = all_country_metadata();
        assert!(all.len() >= 249);
    }
}
